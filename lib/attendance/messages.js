export function monthLabel(monthKey) {
  const [y, m] = monthKey.split('-').map(Number)
  return `${MONTHS[m - 1]} ${y}`
}

// Status for one employee from the rolling 180-day total (same bands as the dashboard).
export function statusOf(rolling) {
  return thresholdBand(rolling).key
}

// "Oct 1, 2026" style date, as used in the old Zap headers.
export function prettyDate(dateStr) {
  const [y, m, d] = dateStr.split('-').map(Number)
  return new Intl.DateTimeFormat('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' })
    .format(new Date(Date.UTC(y, m - 1, d, 12)))
}

// Plain number as the Zap printed it (0, 0.5, 2.5 ...).
export function num(n) {
  return String(Math.round(Number(n) * 100) / 100)
}

// Personal status DM. `runDate` is the report date (1st of the month, YYYY-MM-DD).
export function statusMessage(row, prevMonth, runDate) {
  const s = STATUS[statusOf(row.rolling)]
  const label = monthLabel(prevMonth)
  return `🗓️ *Monthly Attendance Summary – ${prettyDate(runDate)}*\n\n💼 Employee: ${row.name}\n• Points for ${label}: ${num(row.last)}\n• Rolling 6-month total: ${num(row.rolling)}\n\n${s.head}\n\n${s.body}\n\n${SEPARATOR}\n\n${NOTICE}`
}

// Same message for an admin, with a header saying whose record it is.
export function adminCopyMessage(row, prevMonth, runDate) {
  return `🔒 *Admin copy* – record of ${row.name}\n\n${statusMessage(row, prevMonth, runDate)}`
}

